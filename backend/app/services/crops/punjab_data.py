def get_punjab_season_context(ref_date: date) -> tuple[SeasonName, SeasonName]:
    """
    Determine the active Punjab agricultural season and the next upcoming planting season
    for a given calendar date.
    """
    month = ref_date.month
    if month in (11, 12, 1, 2, 3):
        current: SeasonName = "Rabi"
        upcoming: SeasonName = "Zaid" if month in (2, 3) else "Rabi"
        if month in (11, 12):
            upcoming = "Rabi"
        elif month == 1:
            upcoming = "Zaid"
        return current, upcoming
    if month in (4, 5):
        return "Zaid", "Kharif"
    # June to October
    if month in (9, 10):
        return "Kharif", "Rabi"
    return "Kharif", "Kharif"


def get_crops_by_season(season: SeasonName) -> list[CropInfo]:
    return [c for c in PUNJAB_CROPS.values() if c.season == season]
